@dataclass
class ARMInstruction:
    """Parsed ARM instruction"""
    label: str = ""
    opcode: str = ""
    cond: str = ""            # condition code: eq, ne, lt, ge, gt, le, etc.
    s_flag: bool = False      # 'S' suffix (updates flags)
    operands: list = field(default_factory=list)
    comment: str = ""
    raw: str = ""
    line_num: int = 0
    is_directive: bool = False
    is_label: bool = False


def parse_arm_register(s: str) -> str:
    """Normalize ARM register name"""
    s = s.strip().lower()
    # Handle aliases
    aliases = {'a1': 'r0', 'a2': 'r1', 'a3': 'r2', 'a4': 'r3',
               'v1': 'r4', 'v2': 'r5', 'v3': 'r6', 'v4': 'r7',
               'v5': 'r8', 'sb': 'r9', 'sl': 'r10', 'fp': 'fp',
               'ip': 'ip', 'sp': 'sp', 'lr': 'lr', 'pc': 'pc'}
    return aliases.get(s, s)


def parse_immediate(s: str) -> int:
    """Parse ARM immediate value: #123, #0xFF, #-5"""
    s = s.strip().lstrip('#')
    if s.startswith('0x') or s.startswith('0X'):
        return int(s, 16)
    elif s.startswith('-0x') or s.startswith('-0X'):
        return -int(s[1:], 16)
    else:
        return int(s)


def parse_arm_line(line: str, line_num: int) -> Optional[ARMInstruction]:
    """Parse a single line of ARM assembly"""
    inst = ARMInstruction(raw=line, line_num=line_num)

    # Strip comment
    if '@' in line:
        idx = line.index('@')
        inst.comment = line[idx:]
        line = line[:idx]
    if '//' in line:
        idx = line.index('//')
        inst.comment = line[idx:]
        line = line[:idx]

    line = line.strip()
    if not line:
        return None

    # Check for label
    if line.endswith(':'):
        inst.label = line[:-1].strip()
        inst.is_label = True
        return inst

    # Detect label: at start of line
    m = re.match(r'^(\w+):\s*(.*)', line)
    if m:
        inst.label = m.group(1)
        line = m.group(2).strip()
        if not line:
            inst.is_label = True
            return inst

    # Directives
    if line.startswith('.'):
        inst.opcode = line
        inst.is_directive = True
        return inst

    # Data directive (.word)
    if line.startswith('.word'):
        inst.opcode = '.word'
        inst.operands = [line[5:].strip()]
        inst.is_directive = True
        return inst

    # Parse instruction
    parts = line.split(None, 1)
    if not parts:
        return None

    mnemonic = parts[0].lower()
    operand_str = parts[1] if len(parts) > 1 else ""

    # Extract condition code and S flag
    cond_codes = ['eq', 'ne', 'cs', 'hs', 'cc', 'lo', 'mi', 'pl',
                  'vs', 'vc', 'hi', 'ls', 'ge', 'lt', 'gt', 'le', 'al']

    # Special handling for known mnemonics that end with condition-like suffixes
    base_opcodes = ['add', 'sub', 'rsb', 'adc', 'sbc', 'rsc',
                    'and', 'orr', 'eor', 'bic', 'mvn', 'mov',
                    'cmp', 'cmn', 'tst', 'teq',
                    'ldr', 'str', 'ldm', 'stm', 'lsl', 'lsr', 'asr',
                    'mul', 'mla',
                    'push', 'pop',
                    'b', 'bl', 'bx', 'blx',
                    'nop', 'swi', 'svc']

    inst.cond = ''
    inst.s_flag = False

    # Try to match base opcode
    matched = False
    for base in sorted(base_opcodes, key=len, reverse=True):
        if mnemonic.startswith(base):
            rest = mnemonic[len(base):]
            inst.opcode = base

            # Check for condition code
            for cc in cond_codes:
                if rest.startswith(cc):
                    inst.cond = cc
                    rest = rest[len(cc):]
                    break

            # Check for S flag
            if rest == 's':
                inst.s_flag = True
                rest = ''

            # Handle ldr/str variants: ldrb, ldrh, strb, strh
            if base in ('ldr', 'str') and rest in ('b', 'h', 'sb', 'sh'):
                inst.opcode = base + rest
                rest = ''

            # ldmia, stmia etc
            if base in ('ldm', 'stm') and rest in ('ia', 'ib', 'da', 'db',
                                                     'ia!', 'ib!', 'da!', 'db!'):
                inst.opcode = base + rest.rstrip('!')
                rest = ''

            if rest == '' or rest == 's':
                if rest == 's':
                    inst.s_flag = True
                matched = True
                break

    if not matched:
        # Fallback: treat entire mnemonic as opcode
        inst.opcode = mnemonic

    # Parse operands
    if operand_str:
        # Handle register list {r0, r1, r2, r3}
        if '{' in operand_str:
            # Split before and after the braces
            pre = operand_str[:operand_str.index('{')].strip().rstrip(',')
            brace_content = operand_str[operand_str.index('{')+1:operand_str.index('}')]
            post = operand_str[operand_str.index('}')+1:].strip()

            if pre:
                inst.operands.append(pre.strip())
            inst.operands.append('{' + brace_content + '}')
            if post and post != '!':
                inst.operands.append(post)
            if '!' in operand_str:
                inst.operands.append('!')
        else:
            # Handle [base, #offset] memory operands
            # Split by comma, but not inside brackets
            ops = []
            depth = 0
            current = ''
            for ch in operand_str:
                if ch == '[':
                    depth += 1
                    current += ch
                elif ch == ']':
                    depth -= 1
                    current += ch
                elif ch == ',' and depth == 0:
                    ops.append(current.strip())
                    current = ''
                else:
                    current += ch
            if current.strip():
                ops.append(current.strip())
            inst.operands = ops

    return inst


def parse_register_list(s: str) -> List[str]:
    """Parse ARM register list: {r0, r1, r2-r5, lr}"""
    s = s.strip('{}').strip()
    regs = []
    for part in s.split(','):
        part = part.strip()
        if '-' in part:
            # Range: r2-r5
            start, end = part.split('-')
            start = start.strip()
            end = end.strip()
            start_num = int(re.search(r'\d+', start).group())
            end_num = int(re.search(r'\d+', end).group())
            for i in range(start_num, end_num + 1):
                regs.append(f'r{i}')
        else:
            regs.append(parse_arm_register(part))
    return regs


def parse_memory_operand(s: str) -> Tuple[str, int, bool]:
    """Parse ARM memory operand: [r3, #-52] -> (reg, offset, pre_index)
    Returns (base_reg, offset, writeback)"""
    s = s.strip()
    # [reg, #imm]
    m = re.match(r'\[(\w+),\s*#(-?\w+)\](!)?', s)
    if m:
        return parse_arm_register(m.group(1)), parse_immediate(m.group(2)), m.group(3) == '!'
    # [reg]
    m = re.match(r'\[(\w+)\](!)?', s)
    if m:
        return parse_arm_register(m.group(1)), 0, m.group(2) == '!'
    # Just a register (for ldm/stm)
    return parse_arm_register(s), 0, False


