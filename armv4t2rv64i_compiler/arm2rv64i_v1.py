def main():
    parser = argparse.ArgumentParser(
        description='ARM (ARMv4T) to RV64I Cross-Translator',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s sort.s -o sort
  %(prog)s sort.s --verilog --hex --asm
  %(prog)s sort.s --base-addr 0x200 -o thread1

Register Mapping (ARM -> RV64I):
  r0-r12  -> x10-x22
  sp(r13) -> x2
  lr(r14) -> x1
  fp(r11) -> x8
  ip(r12) -> x22
        """)
    parser.add_argument('input', help='Input ARM assembly file (.s)')
    parser.add_argument('-o', '--output', default=None,
                        help='Output file prefix (default: input name)')
    parser.add_argument('--base-addr', type=lambda x: int(x, 0), default=0,
                        help='Base address for generated code (default: 0)')
    parser.add_argument('--hex', action='store_true', help='Generate .hex file')
    parser.add_argument('--asm', action='store_true', help='Generate .S assembly file')
    parser.add_argument('--verilog', action='store_true', help='Generate Verilog init')
    parser.add_argument('--all', action='store_true', help='Generate all output formats')
    parser.add_argument('-v', '--verbose', action='store_true', help='Verbose output')

    args = parser.parse_args()

    if args.all:
        args.hex = args.asm = args.verilog = True

    # Default: generate everything
    if not (args.hex or args.asm or args.verilog):
        args.hex = args.asm = args.verilog = True

    output_prefix = args.output or args.input.rsplit('.', 1)[0]

    # Read input
    with open(args.input, 'r') as f:
        lines = f.readlines()

    # Translate
    translator = ARM2RV64Translator(base_addr=args.base_addr)
    translator.parse(lines)
    translator.translate()

    # Print summary
    print(translator.get_summary())

    # Generate outputs
    if args.asm:
        outfile = f"{output_prefix}_rv64i.S"
        with open(outfile, 'w') as f:
            f.write(f"# Auto-generated RV64I assembly from {args.input}\n")
            f.write(f"# Base address: 0x{args.base_addr:04X}\n\n")
            f.write(translator.get_asm())
        print(f"\n  RV64I assembly written to: {outfile}")

    if args.hex:
        outfile = f"{output_prefix}_rv64i.hex"
        with open(outfile, 'w') as f:
            f.write(translator.get_hex())
        print(f"  Hex file written to: {outfile}")

    if args.verilog:
        outfile = f"{output_prefix}_rv64i.v"
        with open(outfile, 'w') as f:
            f.write(f"// Auto-generated Verilog init from {args.input}\n")
            f.write(f"// Base address: 0x{args.base_addr:04X}\n\n")
            f.write(translator.get_verilog())
        print(f"  Verilog init written to: {outfile}")

    if args.verbose:
        print(f"\n{'=' * 60}")
        print("Generated RV64I Assembly:")
        print('=' * 60)
        print(translator.get_asm())


if __name__ == '__main__':
    main()