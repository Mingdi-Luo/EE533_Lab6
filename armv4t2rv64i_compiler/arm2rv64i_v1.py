# ARM r0-r15 -> RV64I register numbers
ARM_TO_RV = {
    'r0': 10, 'r1': 11, 'r2': 12, 'r3': 13,
    'r4': 14, 'r5': 15, 'r6': 16, 'r7': 17,
    'r8': 18, 'r9': 19, 'r10': 20, 'r11': 21,
    'r12': 22,
    'sp': 2, 'r13': 2,       # stack pointer
    'lr': 1, 'r14': 1,       # link register
    'fp': 8,                   # frame pointer (r11 alias)
    'ip': 22,                  # intra-procedure scratch (r12 alias)
    'pc': -1,                  # program counter (special)
}

# RV64I temp registers for scratch use during translation
RV_TEMP1 = 30  # x30 (t5) - translator scratch 1
RV_TEMP2 = 29  # x29 (t4) - translator scratch 2
RV_ZERO  = 0   # x0


