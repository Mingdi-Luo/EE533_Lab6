#!/usr/bin/env python3
"""
ARM-to-RV64I Cross Translator
==============================

Translates ARMv4T (arm7tdmi) assembly into RV64I machine code.

This tool reads ARM assembly files (as generated by `arm-none-eabi-gcc -S`)
and produces:
  1. Equivalent RV64I assembly (.S file)
  2. RV64I machine code hex (.hex file)
  3. Verilog memory initialization statements (.v file)

Supported ARM instructions (subset for bubble sort and similar programs):
  - Data processing: mov, add, sub, and, orr, eor, lsl, lsr, asr, cmp, rsb, mvn
  - Multiply: mul
  - Load/Store: ldr, str, ldrb, strb, ldrh, strh
  - Multi load/store: ldmia, stmia, ldm, stm (expanded to individual ld/sd)
  - Branch: b, bge, bgt, blt, ble, beq, bne, bx
  - Stack: push, pop
  - Immediate shifts: lsl/lsr/asr as part of data processing

Register mapping (ARM -> RV64I):
  ARM r0-r12  -> RV64I x10-x22 (a0-a2, a3-a7, s2-s6)
  ARM sp (r13) -> RV64I x2 (sp)
  ARM lr (r14) -> RV64I x1 (ra)
  ARM pc (r15) -> (not directly mapped)
  ARM fp (r11) -> RV64I x8 (s0/fp)
  ARM ip (r12) -> RV64I x22 (s6, scratch)

Usage:
  python3 arm2rv64i.py input.s [-o output_prefix] [--base-addr 0x000]
  python3 arm2rv64i.py sort.s -o sort --verilog --hex

生成所有格式（.S汇编 + .hex + .v Verilog初始化）
python3 arm2rv64i.py sort.s -o sort --all

指定线程起始地址（用于多线程）
python3 arm2rv64i.py prog1.s --base-addr 0x200 -o thread1

只生成Verilog初始化
python3 arm2rv64i.py sort.s --verilog

Author: Generated for EE533 Lab 6
"""

